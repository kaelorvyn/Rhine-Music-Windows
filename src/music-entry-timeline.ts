export function Se(i: Keyframes, e: number): number {
  if (e <= i[0][0]) return i[0][1];
  const t = i.length - 1;
  if (e >= i[t][0]) return i[t][1];
  const s = (l: number) => (i[l + 1][1] - i[l][1]) / (i[l + 1][0] - i[l][0]),
    n = (l: number) => {
      if (l === 0) return s(0);
      if (l === t) return s(t - 1);
      const c = s(l - 1),
        u = s(l);
      if (c * u <= 0) return 0;
      const d = i[l][0] - i[l - 1][0],
        p = i[l + 1][0] - i[l][0],
        f = 2 * p + d,
        b = p + 2 * d;
      return (f + b) / (f / c + b / u);
    };
  let a = 0;
  for (; e > i[a + 1][0];) a++;
  const r = i[a + 1][0] - i[a][0],
    o = (e - i[a][0]) / r;
  return (
    (2 * o ** 3 - 3 * o ** 2 + 1) * i[a][1] +
    (o ** 3 - 2 * o ** 2 + o) * r * n(a) +
    (-2 * o ** 3 + 3 * o ** 2) * i[a + 1][1] +
    (o ** 3 - o ** 2) * r * n(a + 1)
  );
}
